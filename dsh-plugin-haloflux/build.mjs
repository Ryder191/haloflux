/**
 * Assemble src/*.js into the single client artifact `client.js`.
 *
 * The Web module loader takes exactly one file per package, so the fragments
 * are concatenated in dependency order inside the loader factory. Every
 * fragment is a plain script that declares exactly one top-level symbol; the
 * shared scope gives them `React` and each other.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const order = ['engine.js', 'state.js', 'live.js', 'hud.js', 'settings.js', 'mount.js'];

const fragments = order.map((file) => {
  const abs = path.join(root, 'src', file);
  if (!fs.existsSync(abs)) throw new Error(`missing fragment: src/${file}`);
  const code = fs.readFileSync(abs, 'utf8').trimEnd();
  return `    /* ================= src/${file} ================= */\n${code
    .split('\n')
    .map((line) => (line.length > 0 ? '    ' + line : line))
    .join('\n')}\n`;
});

const out = `// GENERATED by build.mjs - do not edit. dsh-haloflux.
window.__ModuleLoader__.load({
  id: 'dsh-haloflux',
  factory(require) {
    const React = require('react');
${fragments.join('\n')}
    return HalofluxPlugin;
  },
});
`;

const dest = path.join(root, 'client.js');
fs.writeFileSync(dest, out);
console.log(`client.js written: ${(out.length / 1024).toFixed(1)} KB`);